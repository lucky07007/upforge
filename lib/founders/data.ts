// Helper functions
export function getFounderBySlug(slug: string): Founder | undefined {
  return FOUNDERS.find(f => f.slug === slug)
}

export function getFeaturedFounders(limit = 3): Founder[] {
  return FOUNDERS.filter(f => f.featured).slice(0, limit)
}

export function getAllFounders(page = 1, limit = 9): { founders: Founder[], total: number } {
  const start = (page - 1) * limit
  const end = start + limit
  return {
    founders: FOUNDERS.slice(start, end),
    total: FOUNDERS.length
  }
}

export function getCategorySlug(category?: string): string {
  if (!category) return "general"
  return category
    .toLowerCase()
    .replace(/&/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

export function getFoundersByCategory(categorySlug: string): Founder[] {
  return FOUNDERS.filter(f => getCategorySlug(f.category) === categorySlug)
}

export function getAllCategories(): { name: string; slug: string; count: number }[] {
  const map = new Map<string, { name: string; slug: string; count: number }>()
  FOUNDERS.forEach(f => {
    const catName = f.category || "General"
    const catSlug = getCategorySlug(catName)
    const existing = map.get(catSlug)
    if (existing) {
      existing.count += 1
    } else {
      map.set(catSlug, { name: catName, slug: catSlug, count: 1 })
    }
  })
  return Array.from(map.values())
}

export function getCountrySlug(country?: string): string {
  if (!country) return "all"
  return country
    .toLowerCase()
    .replace(/&/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

export function getCountryFlag(countryOrCode?: string): string {
  if (!countryOrCode) return "🌐"
  const clean = countryOrCode.trim().toUpperCase()
  const map: Record<string, string> = {
    US: "🇺🇸", "UNITED STATES": "🇺🇸",
    FR: "🇫🇷", "FRANCE": "🇫🇷",
    IN: "🇮🇳", "INDIA": "🇮🇳",
    SG: "🇸🇬", "SINGAPORE": "🇸🇬",
    CN: "🇨🇳", "CHINA": "🇨🇳",
    CA: "🇨🇦", "CANADA": "🇨🇦",
    GB: "🇬🇧", UK: "🇬🇧", "UNITED KINGDOM": "🇬🇧",
    SE: "🇸🇪", "SWEDEN": "🇸🇪",
    AU: "🇦🇺", "AUSTRALIA": "🇦🇺",
    BR: "🇧🇷", "BRAZIL": "🇧🇷",
  }
  return map[clean] || "🌐"
}

export function getAllCountries(): { name: string; slug: string; code: string; count: number; flag: string }[] {
  const map = new Map<string, { name: string; slug: string; code: string; count: number; flag: string }>()
  FOUNDERS.forEach(f => {
    const cName = f.country || "United States"
    const cSlug = getCountrySlug(cName)
    const cCode = f.countryCode || "US"
    const existing = map.get(cSlug)
    if (existing) {
      existing.count += 1
    } else {
      map.set(cSlug, {
        name: cName,
        slug: cSlug,
        code: cCode,
        count: 1,
        flag: getCountryFlag(cName)
      })
    }
  })
  return Array.from(map.values()).sort((a, b) => b.count - a.count)
}

export function getFoundersByCountry(countrySlug: string): Founder[] {
  if (!countrySlug || countrySlug === "all") return FOUNDERS
  return FOUNDERS.filter(f => getCountrySlug(f.country) === countrySlug || f.countryCode?.toLowerCase() === countrySlug)
}

export function getRelatedFounders(currentSlug: string, limit = 3): Founder[] {
  const current = getFounderBySlug(currentSlug)
  if (!current) return []
  
  const currentCatSlug = getCategorySlug(current.category)
  
  // Prefer same category, then fallback to same country or general list
  const sameCat = FOUNDERS.filter(f => f.slug !== currentSlug && getCategorySlug(f.category) === currentCatSlug)
  if (sameCat.length >= limit) return sameCat.slice(0, limit)
  
  const rest = FOUNDERS.filter(f => f.slug !== currentSlug && getCategorySlug(f.category) !== currentCatSlug)
  return [...sameCat, ...rest].slice(0, limit)
}

export function getAdjacentFounders(slug: string): { prev: Founder | null, next: Founder | null } {
  const index = FOUNDERS.findIndex(f => f.slug === slug)
  return {
    prev: index > 0 ? FOUNDERS[index - 1] : null,
    next: index < FOUNDERS.length - 1 ? FOUNDERS[index + 1] : null
  }
}



